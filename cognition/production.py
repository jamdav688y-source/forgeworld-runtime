def _scene(index: int, title: str, label: str, refs, citations, disclosures, narration, on_screen, transition,
           shots, visual, audio, audience: str = presentation.VIEWER) -> dict:
    stable = hashlib.sha256(f"{index}|{label}|{title}".encode("utf-8")).hexdigest()[:12]
    return {"scene_id": f"scene-{index:02d}-{stable}", "order": index, "title": title, "label": label,
            "audience": audience,
            "source_refs": sorted(set(refs)), "citations": sorted(set(citations)), "disclosures": disclosures,
            "narration_guidance": narration["guidance"], "narration_lines": narration["lines"],
            "on_screen_text": on_screen, "transition": transition, "shot_list": shots,
            "visual_generation_prompts": visual, "audio": audio,
            "production_instructions": "Produce only after a human checks this scene against its cited records. "
                                       "No footage, narration or imagery exists yet."}


class PackageBuilder:
    def __init__(self, studio, root: Path):
        self.studio = studio
        self.runner = studio.runner
        self.exchange = studio.exchange
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)

    @property
    def grants_execution_authority(self) -> bool:
        return False

    # -- revalidation -------------------------------------------------------------

    def _approval(self, candidate_id: str) -> dict:
        status = self.studio.production_status(candidate_id)
        valid = sorted((r for r in status["reviews"] if r["decision"] == ep.APPROVED and r["valid"]),
                       key=lambda r: r["review_id"])
        if status["status"] != ep.APPROVED or not valid:
            raise PackageError([P_NOT_APPROVED] + sorted({p for r in status["reviews"] for p in r["problems"]}))
        return valid[0]

    def _record(self, record_id: str):
        try:
            record = self.exchange.get_record(record_id)
        except (envelope.LedgerIntegrityError, OSError, ValueError):
            raise PackageError([P_ALTERED_SOURCE]) from None
        if record is None:
            raise PackageError([P_MISSING_SOURCE])
        return record

    # -- build ----------------------------------------------------------------------

    def build(self, candidate_id: str, observed_at: str) -> dict:
        try:
            approval = self._approval(candidate_id)
        except envelope.LedgerIntegrityError:
            raise PackageError([P_ALTERED_SOURCE]) from None
        candidate = self._record(candidate_id)
        review = self._record(approval["review_id"])
        c, r = candidate.payload(), review.payload()
        artifact = self.runner.load(c["cycle_artifact_id"])
        cited = sorted(set(c["input_record_ids"]) | set(c["lens_output_ids"]) | set(c["contradiction_ids"]))
        records = {rid: self._record(rid) for rid in cited}

        package = self._assemble(candidate, c, review, r, artifact, records)
        problems = validate_package(package)
        if problems:
            raise PackageError(problems)
        package_json = cxp.canonical_bytes(package)
        package_id = cxp.digest_id("package", package)
        markdown = render_markdown(package_id, package).encode("utf-8")
        payload = {"package_id": package_id, "package_sha256": _sha(package_json), "markdown_sha256": _sha(markdown),
                   "candidate_id": candidate_id, "review_id": approval["review_id"], "cycle_id": c["cycle_id"],
                   "package_version": c["revision"], "status": DRAFT_PACKAGE, "publication_authorized": False}
        receipt = self.exchange.ingest({
            "schema_version": cxp.SCHEMA_VERSION, "kind": cxp.KIND_PRODUCTION_PACKAGE,
            "representation": cxp.REP_DRAMATIZATION, "evidence": cxp.EV_NONE, "verification": cxp.VER_UNVERIFIED,
            "provenance": cxp.UNVERIFIED_INTERPRETATION, "privacy": candidate.privacy, "payload": payload,
            "sources": [], "derived_from": sorted([candidate_id, approval["review_id"]]), "verification_ref": None,
            "consent_ref": None,
            "occurrence": {"emitter_id": "package-builder", "observed_at": observed_at, "correlation_id": c["cycle_id"],
                           "causation_id": None}})
        if receipt.status == "REJECTED":
            raise PackageError([f"{receipt.error_code}: {receipt.detail}"])
        manifest = {
            "schema": PACKAGE_SCHEMA, "package_id": package_id, "package_record_id": receipt.record_id,
            "package_version": c["revision"], "status": DRAFT_PACKAGE, "publication_authorized": False,
            "generated_media_exists": False,
            "files": {"package.json": _sha(package_json), "package.md": _sha(markdown)},
            "approval": {"review_id": approval["review_id"], "reviewer": r["reviewer"],
                         "accepted_uncertainties": r["accepted_uncertainties"], "acceptance_is_not_verification": True},
            "lineage": {"candidate_id": candidate_id, "candidate_content_id": candidate.content_id,
                        "cycle_id": c["cycle_id"], "cycle_artifact_id": c["cycle_artifact_id"],
                        "assembly_id": c["assembly_id"],
                        "records": [{"record_id": rid, "kind": records[rid].kind, "content_id": records[rid].content_id}
                                    for rid in cited]},
        }
        directory = self.root / package_id
        directory.mkdir(parents=True, exist_ok=True)
        for name, data in (("package.json", package_json), ("package.md", markdown),
                           ("manifest.json", cxp.canonical_bytes(manifest))):
            path = directory / name
            if not path.exists() or path.read_bytes() != data:
                envelope._atomic_write_bytes(path, data)
        return {"package_id": package_id, "package_record_id": receipt.record_id, "directory": str(directory),
                "manifest": manifest, "package": package}

    def _assemble(self, candidate, c, review, r, artifact, records) -> dict:
        assembly = artifact["assembly"]
        sources = {}
        for rid in c["input_record_ids"]:
            for s in lineage.trace(self.exchange.record_metadata, rid)["sources"]:
                sources[s["source_id"]] = {"record_id": rid, "source_type": s["source_type"], "locator": s["locator"],
                                           "independence_basis": s["independence_basis"]}
        locators = sorted(s["locator"] for s in sources.values() if s["locator"])
        by_lens = {r_["lens_id"]: r_ for r_ in assembly["lens_results"] if r_["available"]}
        unsupported = c["unsupported_claims"]
        open_contradictions = [d for d in artifact["preserved_disagreements"] if d["contradiction_id"] in c["contradiction_ids"]]
        experiments = [k for k in artifact.get("research_candidates", []) if k["type"] == "EXPERIMENT"]
        questions = [records[q].payload()["statement"] for q in c["audience_question_ids"]]
        pres = presentation.present(c, open_contradictions, questions, experiments)
        audience_of = {d["contradiction_id"]: d for d in pres["contradiction_disclosures"]}
        uncertainty_note = (f"Disclose on screen: {len(open_contradictions)} open disagreement(s) and "
                            f"{len(unsupported)} unsupported claim(s); none is settled by this episode.")
        scenes, i = [], 0

        def add(*args):
            nonlocal i
            i += 1
            scenes.append(_scene(i, *args))

        if questions:
            add("Cold open: the audience asked", QUOTED_SOURCE, c["audience_question_ids"], locators,
                ["Quoted verbatim from an audience comment; it shows that someone asked, nothing more."],
                {"guidance": "Read the question exactly as written. Do not answer it yet.", "lines": questions},
                questions[0], "Cut to title card.",
                ["Close-up: the question on screen as text, no commenter name or avatar.",
                 "Slow push-in on the text."],
                ["Minimal dark background with the audience question as on-screen typography; no faces, no platform logos."],
                {"music": "sparse, unresolved", "pacing": "slow, 8-12 seconds"})
        for act in c["acts"]:
            add(f"{act['label'].replace('_', ' ').title()}: dramatized", DRAMATIZATION,
                [candidate.record_id] + ([by_lens["STORYWEAVER"]["record_id"]] if "STORYWEAVER" in by_lens else []), [],
                [c["dramatization_label"], uncertainty_note],
                {"guidance": "Narrate as a dramatization. Say it is a reconstruction, not footage of real events.",
                 "lines": [act["text"]]},
                "DRAMATIZATION", "Bridge into the next beat with a visual match cut.",
                ["Wide: establish the two devices as abstract shapes.", "Medium: the request travelling between them.",
                 "Insert: on-screen label DRAMATIZATION held for the whole scene."],
                [f"Stylized, clearly illustrative animation of: {act['text']} Label the frame DRAMATIZATION."],
                {"music": "low tension, restrained", "pacing": "medium, 30-45 seconds"})
        for d in open_contradictions:
            refs = [d["contradiction_id"]] + [by_lens[l]["record_id"] for p in d["positions"].values() for l in p if l in by_lens]
            lines = [f"{lens}: {by_lens[lens]['statement']}" for p in ("SUPPORT", "OPPOSE") for lens in d["positions"].get(p, [])
                     if lens in by_lens]
            view = audience_of[d["contradiction_id"]]
            internal = view["audience"] == presentation.INTERNAL_ONLY
            add(("Production note (internal): " if internal else "Where the analysis disagrees: ") + view["viewer_phrasing"],
                INTERPRETATION, refs, [],
                [f"OPEN contradiction {d['contradiction_id']}: the lenses disagree and nothing has resolved it.",
                 "These are rule-based interpretations, not findings."]
                + (["Internal production question: not intended for broadcast; it stays in the production notes."]
                   if internal else []),
                {"guidance": "Present both sides with equal weight. Do not pick a winner.", "lines": lines},
                "Not for broadcast" if internal else f"Unresolved: {view['viewer_phrasing']}",
                "Hold on the split screen, then cut.",
                ["Split screen: SUPPORT on the left, OPPOSE on the right.", "Lower third: OPEN, UNRESOLVED."],
                ["Two-column typographic layout labelled SUPPORT and OPPOSE; neutral colours, no winner implied."],
                {"music": "pause or near-silence", "pacing": "slow, let both sides breathe"},
                presentation.INTERNAL_ONLY if internal else presentation.VIEWER)
        add("What we do not know yet", HYPOTHESIS,
            [candidate.record_id] + ([by_lens["SCIENTIST"]["record_id"]] if "SCIENTIST" in by_lens else [])
            + ([by_lens["CATALYST"]["record_id"]] if "CATALYST" in by_lens else []), [],
            ["Hypotheses and proposed experiments only; nothing here has been run."] +
            [f"UNSUPPORTED: {claim}" for claim in pres["claims_requiring_disclosure"]] +
            [f"AUDIENCE QUESTION (asked, not a claim): {q}" for q in pres["audience_questions_asked"]],
            {"guidance": "Frame each item as an open question or a test we could run, never as a result.",
             "lines": [k["proposal"] for k in experiments if k.get("proposal")] + pres["uncertainty_disclosures"][:3]},
            "Open questions", "Fade to end card.",
            ["Slow list build of open questions on screen.", "End card: invitation to ask questions."],
            ["Clean list layout of open questions with a 'not yet tested' tag on each."],
            {"music": "light, curious", "pacing": "medium"})

        intake_questions = pres["viewer_open_questions"]
        return {
            "schema": PACKAGE_SCHEMA,
            "status": DRAFT_PACKAGE,
            "publication_authorized": False,
            "generated_media_exists": False,
            "episode_title": c["working_title"],
            "intended_audience": {"description": f"YouTube viewers curious about {artifact.get('topic') or 'this topic'}",
                                  "basis": "ASSUMPTION from the motivating audience question's platform; not measured"},
            "scenes": scenes,
            "citation_sheet": [{**s, "record_kind": records[s["record_id"]].kind,
                                "evidence": records[s["record_id"]].evidence,
                                "verification": records[s["record_id"]].verification}
                               for s in sorted(sources.values(), key=lambda s: (s["record_id"], s["locator"] or ""))]
                              + [{"record_id": rid, "record_kind": records[rid].kind, "evidence": records[rid].evidence,
                                  "verification": records[rid].verification, "locator": None,
                                  "source_type": "cxp_record", "independence_basis": None}
                                 for rid in c["lens_output_ids"] + c["contradiction_ids"]],
            "disclosures": {
                "dramatization": c["dramatization_label"],
                "contradictions": [{"contradiction_id": d["contradiction_id"], "question": d["question"],
                                    "status": contradiction.assess(self.exchange, d["contradiction_id"])["status"],
                                    "positions": d["positions"]} for d in open_contradictions],
                "unsupported_claims": [{"claim": claim, "label": "AUDIENCE QUESTION: shown as asked, asserts nothing"
                                        if claim in pres["audience_questions_asked"]
                                        else "UNSUPPORTED: do not present as fact"} for claim in unsupported],
                "open_questions": c["open_questions"],
                "accepted_uncertainty": {"reviewer": r["reviewer"], "accepted": r["accepted_uncertainties"],
                                         "note": "Acceptance means the reviewer chose to proceed with these "
                                                 "uncertainties disclosed. It verifies nothing."},
            },
            "experiment_references": [{"candidate_id": k["candidate_id"], "proposal": k.get("proposal"),
                                       "status": k["status"], "evidence_status": k["evidence_status"]} for k in experiments],
            "audio_plan": {"overall": "restrained score; silence under contradictions; no stingers implying revelation",
                           "voice": "calm, explanatory; slows down for every disclosure"},
            "thumbnail_concepts": [f"Concept A: the title '{c['working_title']}' over a locked padlock between two devices, "
                                   "small corner tag DRAMATIZATION",
                                   "Concept B: a question mark over a phone and a PC, tag OPEN QUESTION"],
            "opening_hook_concepts": ([f"Open on the viewer's question: '{questions[0]}'"] if questions else []) +
                                     ["Open on the unresolved disagreement before naming it"],
            "youtube_description_draft": (
                f"{c['working_title']}\n\nThis episode is a dramatization built from an audience question and a "
                "rule-based analysis. It contains open disagreements and unsupported claims, listed below; none are "
                "settled here.\n\nSources:\n" + "\n".join(f"- {loc}" for loc in locators) +
                "\n\nOpen disagreements: " + str(len(open_contradictions)) +
                "\nUnsupported claims: " + str(len(unsupported))),
            "pinned_comment_draft": "What would change your mind on the open questions in this episode? "
                                    "Your questions may shape the next one.",
            "future_intake_questions": intake_questions,
            "presentation": pres,
            "lineage": {"candidate_id": candidate.record_id, "candidate_revision": c["revision"],
                        "cycle_id": c["cycle_id"], "cycle_artifact_id": c["cycle_artifact_id"],
                        "assembly_id": c["assembly_id"], "lens_output_ids": c["lens_output_ids"],
                        "contradiction_ids": c["contradiction_ids"], "input_record_ids": c["input_record_ids"],
                        "audience_question_ids": c["audience_question_ids"], "unsupported_claims": unsupported,
                        "open_questions": c["open_questions"], "review_id": review.record_id},
            "governance": {"recursion": "this package is recycled cognition to R4; it can never start or justify a cycle",
                           "production_approval_is_not_publication_approval": True},
        }

    # -- load ---------------------------------------------------------------------------

    def load(self, package_id: str) -> dict:
        """Read an exported package back, failing closed on any tampering."""
        directory = self.root / package_id
        try:
            package_bytes = (directory / "package.json").read_bytes()
            markdown = (directory / "package.md").read_bytes()
            manifest = json.loads((directory / "manifest.json").read_bytes())
            package = json.loads(package_bytes)
        except (OSError, ValueError):
            raise PackageError([P_TAMPERED]) from None
        if (cxp.digest_id("package", package) != package_id or manifest.get("package_id") != package_id
                or manifest.get("files") != {"package.json": _sha(package_bytes), "package.md": _sha(markdown)}
                or manifest.get("publication_authorized") is not False or manifest.get("status") != DRAFT_PACKAGE):
            raise PackageError([P_TAMPERED])
        record = self.exchange.record_metadata(manifest["package_record_id"])
        if record is None or record["kind"] != cxp.KIND_PRODUCTION_PACKAGE:
            raise PackageError([P_TAMPERED])
        anchored = self.exchange.get_record(manifest["package_record_id"]).payload()
        if anchored["package_sha256"] != _sha(package_bytes) or anchored["markdown_sha256"] != _sha(markdown):
            raise PackageError([P_TAMPERED])
        problems = validate_package(package)
        if problems:
            raise PackageError(problems)
        return {"package": package, "manifest": manifest, "markdown": markdown.decode("utf-8")}


def render_markdown(package_id: str, package: dict) -> str:
    """Human-readable export; deterministic for a given package."""
    out = [f"# {package['episode_title']}", "",
           f"`{package_id}` | status **{package['status']}** | publication authorized: **no** | "
           "generated media exists: **no**", "",
           f"> {package['disclosures']['dramatization']}", "",
           f"Intended audience: {package['intended_audience']['description']} "
           f"({package['intended_audience']['basis']})", "", "## Scenes", ""]
    for s in package["scenes"]:
        out += [f"### {s['order']:02d}. {s['title']}  [{s['label']}]" + ("  (INTERNAL ONLY)" if s["audience"] == presentation.INTERNAL_ONLY else ""),
                f"`{s['scene_id']}`", "",
                f"- **Narration guidance:** {s['narration_guidance']}"]
        out += [f"  - \"{line}\"" for line in s["narration_lines"]]
        out += [f"- **On screen:** {s['on_screen_text']}", f"- **Transition:** {s['transition']}",
                f"- **Disclosures:** " + "; ".join(s["disclosures"]),
                f"- **Source refs:** " + ", ".join(f"`{r}`" for r in s["source_refs"])]
        if s["citations"]:
            out.append("- **Citations:** " + ", ".join(s["citations"]))
        out += ["- **Shots:**"] + [f"  - {shot}" for shot in s["shot_list"]]
        out += ["- **Visual prompts (for later, human-approved generation):**"] + [f"  - {v}" for v in s["visual_generation_prompts"]]
        out += [f"- **Audio:** {s['audio']['music']}; pacing {s['audio']['pacing']}",
                f"- **Production:** {s['production_instructions']}", ""]
    d = package["disclosures"]
    out += ["## Disclosures", "", "### Open contradictions"]
    out += [f"- `{c['contradiction_id']}` {c['question']}: **{c['status']}**, positions {json.dumps(c['positions'], sort_keys=True)}"
            for c in d["contradictions"]] or ["- none"]
    out += ["", "### Unsupported claims"] + [f"- {u['claim']} ({u['label']})" for u in d["unsupported_claims"]]
    out += ["", "### Open questions"] + [f"- {q}" for q in d["open_questions"]]
    pres = package["presentation"]
    out += ["", "### Production notes (methodology, not for broadcast)"] + [f"- {n}" for n in pres["methodology_notes"]]
    out += ["", "### Uncertainty to disclose to viewers"] + [f"- {u}" for u in pres["uncertainty_disclosures"]]
    out += ["", f"### Accepted uncertainty", f"Reviewer `{d['accepted_uncertainty']['reviewer']}`: "
            f"{d['accepted_uncertainty']['note']}", "", "## Citation sheet", "",
            "| record | kind | evidence | verification | source |", "|---|---|---|---|---|"]
    out += [f"| `{c['record_id'][:20]}…` | {c['record_kind']} | {c['evidence']} | {c['verification']} | "
            f"{c['locator'] or 'CXP record'} |" for c in package["citation_sheet"]]
    out += ["", "## Experiments referenced"] + [f"- {e['proposal']} ({e['status']}, {e['evidence_status']})"
                                                for e in package["experiment_references"]]
    out += ["", "## Audio plan", f"- {package['audio_plan']['overall']}", f"- Voice: {package['audio_plan']['voice']}",
            "", "## Thumbnail concepts"] + [f"- {t}" for t in package["thumbnail_concepts"]]
    out += ["", "## Opening hooks"] + [f"- {h}" for h in package["opening_hook_concepts"]]
    out += ["", "## YouTube description (draft)", "", "```", package["youtube_description_draft"], "```",
            "", "## Pinned comment (draft)", "", package["pinned_comment_draft"],
            "", "## Questions for future audience intake"] + [f"- {q['question']}" for q in package["future_intake_questions"]]
    out += ["", "---", "Production approval is not publication approval. Nothing here has been published, "
            "uploaded or scheduled.", ""]
    return "\n".join(out)
