"""FW-YOUTUBE-PRODUCTION-E2-001: YouTube production packages.

A production package is ASSEMBLED, not reasoned: it is a deterministic
rearrangement of material that already exists -- one approved
EPISODE_CANDIDATE version, its approving EPISODE_REVIEW, its immutable cycle
artifact, and the CXP records they cite. No lens is re-run, nothing is
generated by a model, and nothing in it is new evidence.

Build-time revalidation (PackageError, nothing written, on any failure):
    the exact candidate version is APPROVED_FOR_PRODUCTION right now
      (E1 production_status: not superseded, not later rejected or sent
      back for revision, approval still valid against the governor ledger
      and the artifact);
    every cited record (inputs, lens outputs, contradictions, the candidate,
      the review) is present, unerased and intact.

Every scene carries a label saying what kind of statement it makes:
    QUOTED_SOURCE   verbatim source text, cited (e.g. the audience question)
    INTERPRETATION  what the lenses concluded, cited to their outputs
    HYPOTHESIS      proposals and experiments, cited, not results
    DRAMATIZATION   narrative scenes, cited to the candidate; not evidence
validate_package() refuses a package where a scene lacks citations, where
verification language appears while the material is unverified, or where
any contradiction, unsupported claim or open question is missing from the
disclosures. It runs at build time and again on every load.

Output: packages/<package_id>/{package.json, package.md, manifest.json}.
package_id is the hash of package.json's canonical content; the manifest
holds the file hashes, every lineage reference with its CXP content_id, and
the approval identity. A thin PRODUCTION_PACKAGE CXP record (derived from
the candidate and the review) anchors the package in lineage; it is never
lens input, never a cycle source, and anything derived from it is recycled
cognition to R4.

THE PUBLICATION BOUNDARY IS FIXED: status is always DRAFT_PACKAGE and
publication_authorized is always False -- in the package, the manifest and
the CXP record. There is no upload, scheduling, posting or messaging code
here, and no media is claimed to exist: visual prompts, narration guidance
and music notes are instructions for a later, separately approved
production step.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

from evidence_envelope import envelope
from cognition import contradiction, cxp, episode as ep, lineage, presentation

PACKAGE_SCHEMA = "forgeworld.production.package.v2"  # v2: lens v2 presentation
DRAFT_PACKAGE = "DRAFT_PACKAGE"

QUOTED_SOURCE = "QUOTED_SOURCE"
INTERPRETATION = "INTERPRETATION"
HYPOTHESIS = "HYPOTHESIS"
DRAMATIZATION = "DRAMATIZATION"
SCENE_LABELS = (QUOTED_SOURCE, INTERPRETATION, HYPOTHESIS, DRAMATIZATION)

P_NOT_APPROVED = "NOT_APPROVED_FOR_PRODUCTION"
P_MISSING_SOURCE = "MISSING_OR_ERASED_SOURCE"
P_ALTERED_SOURCE = "ALTERED_SOURCE"
P_UNCITED_SCENE = "UNCITED_SCENE"
P_BAD_LABEL = "UNKNOWN_SCENE_LABEL"
P_CONTRADICTION_SUPPRESSED = "CONTRADICTION_SUPPRESSED"
P_UNSUPPORTED_UNDISCLOSED = "UNSUPPORTED_CLAIM_UNDISCLOSED"
P_OPEN_QUESTION_UNDISCLOSED = "OPEN_QUESTION_UNDISCLOSED"
P_PRESENTED_AS_VERIFIED = "PRESENTED_AS_VERIFIED"
P_PUBLICATION_FLAG = "PUBLICATION_FLAG_ALTERED"
P_TAMPERED = "PACKAGE_TAMPERED"
P_BAD_AUDIENCE = "UNKNOWN_SCENE_AUDIENCE"

_PAYLOAD_KEYS = frozenset({"package_id", "package_sha256", "markdown_sha256", "candidate_id", "review_id", "cycle_id",
                           "package_version", "status", "publication_authorized"})
_PACKAGE_ID = re.compile(r"^cxp-pkg-[0-9a-f]{64}$")
_SHA256 = re.compile(r"^[0-9a-f]{64}$")
_RECORD_ID = re.compile(r"^cxp-rec-[0-9a-f]{64}$")
_VERIFICATION_LANGUAGE = ep._VERIFICATION_LANGUAGE
_NEGATION = re.compile(r"\b(not|no|never|isn't|wasn't|aren't|nothing)\b[^.;:]{0,30}$", re.IGNORECASE)


def asserts_verification(text: str) -> bool:
    """True when text claims something is verified/proven/confirmed. A
    negated mention ("no input is verified", "not proven") discloses
    uncertainty and does not count."""
    for match in _VERIFICATION_LANGUAGE.finditer(text):
        if not _NEGATION.search(text[:match.start()]):
            return True
    return False
_TEXT_FIELDS = ("title", "on_screen_text", "narration_guidance", "transition")


class PackageError(Exception):
    def __init__(self, reasons):
        super().__init__(", ".join(reasons))
        self.reasons = list(reasons)


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# ---------------------------------------------------------------------------
# CXP record schema (called by cxp)
# ---------------------------------------------------------------------------

def check_record_payload(payload: dict) -> None:
    if set(payload) != _PAYLOAD_KEYS:
        raise cxp.CXPError(cxp.E_MALFORMED, f"PRODUCTION_PACKAGE payload requires exactly {sorted(_PAYLOAD_KEYS)}")
    if not isinstance(payload["package_id"], str) or not _PACKAGE_ID.match(payload["package_id"]):
        raise cxp.CXPError(cxp.E_MALFORMED, "package_id is malformed")
    for name in ("package_sha256", "markdown_sha256"):
        if not isinstance(payload[name], str) or not _SHA256.match(payload[name]):
            raise cxp.CXPError(cxp.E_MALFORMED, f"{name} must be a sha256 hex digest")
    for name in ("candidate_id", "review_id"):
        if not isinstance(payload[name], str) or not _RECORD_ID.match(payload[name]):
            raise cxp.CXPError(cxp.E_MALFORMED, f"{name} must be a record id")
    if payload["status"] != DRAFT_PACKAGE or payload["publication_authorized"] is not False:
        raise cxp.CXPError(cxp.E_KIND_RULE, "a production package is always DRAFT_PACKAGE with publication_authorized false")
    if not isinstance(payload["package_version"], int) or isinstance(payload["package_version"], bool) or payload["package_version"] < 1:
        raise cxp.CXPError(cxp.E_MALFORMED, "package_version must be a positive integer")


def check_record_labels(payload, provenance, representation, evidence, verification, derived_from) -> None:
    if (representation, evidence, verification, provenance) != (
            cxp.REP_DRAMATIZATION, cxp.EV_NONE, cxp.VER_UNVERIFIED, cxp.UNVERIFIED_INTERPRETATION):
        raise cxp.CXPError(cxp.E_KIND_RULE, "a PRODUCTION_PACKAGE is DRAMATIZATION, evidence NONE, UNVERIFIED, "
                                            "UNVERIFIED_INTERPRETATION: assembling material adds no evidence")
    if list(derived_from) != sorted([payload["candidate_id"], payload["review_id"]]):
        raise cxp.CXPError(cxp.E_KIND_RULE, "a PRODUCTION_PACKAGE derives from exactly its candidate and its approving review")


def check_transition(payload: dict, lookup) -> None:
    candidate, review = lookup(payload["candidate_id"]), lookup(payload["review_id"])
    if candidate is None or candidate["kind"] != cxp.KIND_EPISODE_CANDIDATE:
        raise cxp.CXPError(cxp.E_TRANSITION_REFUSED, "candidate_id is not an accepted EPISODE_CANDIDATE")
    if (review is None or review["kind"] != cxp.KIND_EPISODE_REVIEW
            or review["episode_review"]["candidate_id"] != payload["candidate_id"]
            or review["episode_review"]["decision"] != ep.APPROVED):
        raise cxp.CXPError(cxp.E_TRANSITION_REFUSED, "review_id is not an APPROVED review of this exact candidate")
    if candidate["episode"]["cycle_id"] != payload["cycle_id"]:
        raise cxp.CXPError(cxp.E_TRANSITION_REFUSED, "cycle_id does not match the candidate's cycle")


# ---------------------------------------------------------------------------
# validation of a package body (build time and every load)
# ---------------------------------------------------------------------------

def validate_package(package: dict) -> list:
    problems = []
    if package.get("status") != DRAFT_PACKAGE or package.get("publication_authorized") is not False:
        problems.append(P_PUBLICATION_FLAG)
    disclosures = package.get("disclosures", {})
    disclosed_contradictions = {d["contradiction_id"] for d in disclosures.get("contradictions", [])}
    audience_of = {c["contradiction_id"]: c["audience"]
                   for c in package.get("presentation", {}).get("contradiction_disclosures", [])}
    for cid in package.get("lineage", {}).get("contradiction_ids", []):
        # every contradiction stays disclosed; a VIEWER-facing one must also stay on screen
        in_scene = any(cid in s["source_refs"] for s in package.get("scenes", []))
        if (cid not in disclosed_contradictions or cid not in audience_of
                or (audience_of[cid] == presentation.VIEWER and not in_scene)):
            problems.append(P_CONTRADICTION_SUPPRESSED)
            break
    disclosed_claims = {d["claim"] for d in disclosures.get("unsupported_claims", [])}
    if not set(package.get("lineage", {}).get("unsupported_claims", [])) <= disclosed_claims:
        problems.append(P_UNSUPPORTED_UNDISCLOSED)
    if not set(package.get("lineage", {}).get("open_questions", [])) <= set(disclosures.get("open_questions", [])):
        problems.append(P_OPEN_QUESTION_UNDISCLOSED)
    for scene in package.get("scenes", []):
        if scene.get("label") not in SCENE_LABELS:
            problems.append(P_BAD_LABEL)
        if scene.get("audience") not in (presentation.VIEWER, presentation.INTERNAL_ONLY):
            problems.append(P_BAD_AUDIENCE)
        if not scene.get("source_refs"):
            problems.append(P_UNCITED_SCENE)
        texts = [scene.get(k, "") for k in _TEXT_FIELDS] + [line for line in scene.get("narration_lines", [])]
        if any(asserts_verification(t) for t in texts):
            problems.append(P_PRESENTED_AS_VERIFIED)
    for field in ("youtube_description_draft", "pinned_comment_draft"):
        if asserts_verification(package.get(field, "")):
            problems.append(P_PRESENTED_AS_VERIFIED)
    return sorted(set(problems))


